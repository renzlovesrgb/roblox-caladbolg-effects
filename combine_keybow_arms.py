import os
import re
import urllib.request
from pathlib import Path

TOP_URL = "https://github.com/rythmplayzyt/so-meshed-up/raw/refs/heads/main/keybowtop9.obj"
BOTTOM_URL = "https://github.com/rythmplayzyt/so-meshed-up/raw/refs/heads/main/keybowbottom3.obj"
OUT_PATH = Path("keybow_arms_combined.obj")


def download_text(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", errors="replace")


def parse_obj(text: str):
    vertices = []
    faces = []
    current_material = None

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue

        if line.startswith("usemtl "):
            current_material = line.split(maxsplit=1)[1]
            continue

        if line.startswith("v "):
            vertices.append(line)
            continue

        if line.startswith("f "):
            face_tokens = line.split()[1:]
            if not face_tokens:
                continue
            # Convert OBJ vertex indices to 1-based and keep them as-is for later output.
            # We do not split by texture/normal because it is usually "v/vt/vn" format.
            faces.append((current_material, face_tokens))

    return vertices, faces


def merge_meshes(top_obj: str, bottom_obj: str) -> str:
    top_vertices, top_faces = parse_obj(top_obj)
    bottom_vertices, bottom_faces = parse_obj(bottom_obj)

    merged_vertices = list(top_vertices)
    merged_faces = list(top_faces)

    # Offset face indices from the second object by the number of vertices added.
    v_offset = len(merged_vertices)
    for material, face_tokens in bottom_faces:
        merged_faces.append((material, [str(int(v) + v_offset) if v else v for v in face_tokens]))

    merged_vertices.extend(bottom_vertices)

    out_lines = [
        "# Combined Key Bow arm mesh",
        "# Source: keybowtop9.obj + keybowbottom3.obj",
        "# Generated by combine_keybow_arms.py",
    ]

    out_lines.extend(merged_vertices)

    # Reconstruct face lines while preserving face token formats.
    # The face token may include v/vt/vn triplets, but we only need the vertex index.
    for material, face_tokens in merged_faces:
        if material:
            out_lines.append(f"usemtl {material}")
        out_lines.append("f " + " ".join(face_tokens))

    return "\n".join(out_lines) + "\n"


def main():
    top_obj = download_text(TOP_URL)
    bottom_obj = download_text(BOTTOM_URL)
    combined = merge_meshes(top_obj, bottom_obj)
    OUT_PATH.write_text(combined, encoding="utf-8")
    print(f"Saved combined mesh to: {OUT_PATH.resolve()}")


if __name__ == "__main__":
    main()
